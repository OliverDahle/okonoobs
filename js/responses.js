/** Finn riktig svar basert på profil, spørsmål og tone */
export function finnSvar(profilId, sporsmal, toneId) {
  const s = sporsmal.toLowerCase();
  const svar = SVAR[profilId];
  if (!svar) return '';

  let kategori;

  if (profilId === 'emma') {
    if (s.includes('bsu')) kategori = 'bsu';
    else if (s.includes('bolig')) kategori = 'bolig';
    else if (s.includes('fond') || s.includes('investere')) kategori = 'fond';
    else kategori = 'default';
  } else if (profilId === 'andreas') {
    if (s.includes('ips') || (s.includes('skatt') && s.includes('pensjon'))) kategori = 'ips';
    else if (s.includes('nedbetal') || s.includes('lån') || s.includes('boliglån')) kategori = 'laan';
    else if (s.includes('ask') || s.includes('aksjesparekonto')) kategori = 'ask';
    else kategori = 'default';
  } else if (profilId === 'karin') {
    if (s.includes('brukskonto') || s.includes('million') || s.includes('kapital') || s.includes('gjøre')) kategori = 'kapital';
    else if (s.includes('trygg') || s.includes('plasser') || s.includes('avkastning')) kategori = 'trygg';
    else if (s.includes('private')) kategori = 'private';
    else kategori = 'default';
  } else {
    return svar.default || '';
  }

  const respons = svar[kategori];
  if (!respons) return svar.default || '';
  if (typeof respons === 'string') return respons;
  return respons[toneId] || respons.profesjonell || '';
}
